/**
 * Renders the business-policy overview (`docs/POLICY.md`) and the policy block
 * of `infra/docker/env.example/api.env.example` from `POLICY_SCHEMA`, plus the
 * web / driver-app client knob files (RCAB-E8.S10). Pure functions: file I/O
 * lives in `scripts/policy-doc.ts` (`pnpm policy:doc`, `pnpm policy:doc:check`).
 */
import { defaultPolicy, policyKnobs, type KnobEntry } from './policy';
import {
  POLICY_CATEGORIES,
  POLICY_RULES,
  POLICY_SCHEMA,
  type Knob,
  type PolicyCategory,
} from './policy.schema';

export interface ClientKnob {
  key: string;
  value: string;
  unit: string;
  source: 'client' | 'server-mirror';
  description: string;
  decision: string;
}

interface ClientMeta {
  unit: string;
  source: 'client' | 'server-mirror';
  description: string;
  decision: string;
}

export const ENV_BLOCK_START =
  '# >>> business policy — generated by `pnpm policy:doc` from apps/api/src/config/policy/policy.schema.ts; do not edit inside >>>';
export const ENV_BLOCK_END = '# <<< business policy <<<';

// ── Formatting ───────────────────────────────────────────────────────────────

/** 240000 → "4 min", 12000 → "12 s", 2592000000 → "30 d". */
export function humanMs(ms: number): string {
  const units: [number, string][] = [
    [86_400_000, 'd'],
    [3_600_000, 'h'],
    [60_000, 'min'],
    [1000, 's'],
  ];
  for (const [size, label] of units) if (ms >= size && ms % size === 0) return `${ms / size} ${label}`;
  return `${ms} ms`;
}

function defaultValue(entry: KnobEntry): unknown {
  const defaults = defaultPolicy() as unknown as Record<string, Record<string, unknown>>;
  return defaults[entry.category][entry.name];
}

function derivedLabel(knob: Knob): string | null {
  if (knob.type === 'int' || knob.type === 'number' || knob.type === 'duration-ms') {
    return typeof knob.default === 'number' ? null : knob.default.label;
  }
  return null;
}

function formatDefault(entry: KnobEntry): string {
  const { knob } = entry;
  const v = defaultValue(entry);
  if (Array.isArray(v)) return v.map((s) => `\`${String(s)}\``).join(', ');
  if (typeof v === 'number') {
    const human = knob.type === 'duration-ms' ? ` (${humanMs(v)})` : '';
    const label = derivedLabel(knob);
    return `${label ? `${label} = ` : ''}${v}${human}`;
  }
  return `\`${String(v)}\``;
}

export function formatAllowed(knob: Knob): string {
  switch (knob.type) {
    case 'bool':
      return 'true / false';
    case 'enum':
      return knob.allowed.map((s) => `\`${s}\``).join(' / ');
    case 'list':
      return `subset of ${knob.allowed.map((s) => `\`${s}\``).join(', ')}`;
    default: {
      const kind = knob.type === 'number' ? 'number' : 'integer';
      if (knob.min !== undefined && knob.max !== undefined) return `${kind} ${knob.min} – ${knob.max}`;
      if (knob.min !== undefined) return `${kind} ≥ ${knob.min}`;
      if (knob.max !== undefined) return `${kind} ≤ ${knob.max}`;
      return kind;
    }
  }
}

function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function row(cells: string[]): string {
  return `| ${cells.map(cell).join(' | ')} |`;
}

// ── Client knob sources ──────────────────────────────────────────────────────

function leaves(value: unknown, prefix: string, out: Map<string, unknown>): void {
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    for (const [k, v] of Object.entries(value)) leaves(v, prefix ? `${prefix}.${k}` : k, out);
  } else {
    out.set(prefix, value);
  }
}

function formatClientValue(v: unknown): string {
  if (Array.isArray(v)) return `[${v.join(', ')}]`;
  return String(v);
}

/** Flattens WEB_POLICY against WEB_POLICY_META; throws if either side has a key the other lacks. */
export function webKnobs(values: object, meta: Readonly<Record<string, ClientMeta>>): ClientKnob[] {
  const flat = new Map<string, unknown>();
  leaves(values, '', flat);
  const missingMeta = [...flat.keys()].filter((k) => !(k in meta));
  const orphanMeta = Object.keys(meta).filter((k) => !flat.has(k));
  if (missingMeta.length || orphanMeta.length) {
    throw new Error(
      `web policy drift: values without WEB_POLICY_META [${missingMeta.join(', ')}], ` +
        `meta without value [${orphanMeta.join(', ')}]`,
    );
  }
  return [...flat.entries()].map(([key, v]) => ({ key, value: formatClientValue(v), ...meta[key] }));
}

const DART_META_RE = /^unit: (.+?) \| source: (client|server-mirror) \| decision: (.+)$/;

/**
 * Parses `lib/core/config/policy.dart`: every `static const` must be preceded by
 * `///` description line(s) and a `/// unit: … | source: … | decision: …` line.
 */
export function parseDartPolicy(source: string): ClientKnob[] {
  const declared = source.match(/^\s*static const /gm)?.length ?? 0;
  const re = /((?:^[ \t]*\/\/\/.*\n)+)[ \t]*static const [\w<>?]+ (\w+) = ([^;]+);/gm;
  const out: ClientKnob[] = [];
  for (const m of source.matchAll(re)) {
    const docs = m[1]
      .split('\n')
      .map((l) => l.replace(/^\s*\/\/\/ ?/, '').trim())
      .filter(Boolean);
    const meta = DART_META_RE.exec(docs[docs.length - 1] ?? '');
    const description = docs.slice(0, -1).join(' ');
    if (!meta || !description) {
      throw new Error(`driver policy: ${m[2]} needs a description and a "unit: … | source: … | decision: …" line`);
    }
    out.push({
      key: m[2],
      value: m[3].trim(),
      unit: meta[1],
      source: meta[2] as ClientKnob['source'],
      description,
      decision: meta[3],
    });
  }
  if (out.length !== declared) {
    throw new Error(`driver policy: ${declared - out.length} static const(s) without the required doc comment`);
  }
  return out;
}

// ── Renderers ────────────────────────────────────────────────────────────────

export interface ClientKnobSets {
  web: ClientKnob[];
  driver: ClientKnob[];
}

function envOf(key: string): string {
  return policyKnobs().find((k) => k.key === key)?.knob.env ?? key;
}

export function renderPolicyDoc(clients: ClientKnobSets): string {
  const knobs = policyKnobs();
  const categories = Object.keys(POLICY_SCHEMA) as PolicyCategory[];
  const lines: string[] = [];
  const envCount = knobs.filter((k) => k.knob.env).length;

  lines.push(
    '# rcab business policy',
    '',
    '<!-- Generated by `pnpm policy:doc` — do not edit by hand. `pnpm policy:doc:check` (CI lint stage) fails on drift. -->',
    '',
    'Every business decision point of rcab in one place: fares, dispatch, the scheduled window, pool matching,',
    'ride lifecycle, sessions, rate limits, realtime cadence, the outbox loop, and the client-side knobs.',
    '',
    '- **Source of truth (server):** `apps/api/src/config/policy/policy.schema.ts`. The API reads the env vars below',
    '  through it once at boot, validates every value and every cross-field rule, and refuses to start on any',
    '  violation (the error lists every bad key, never the value). Services read the frozen `Policy` object.',
    '- **Change a rule:** edit its `default` and `decision` in the schema (all environments) or set the env var',
    '  (one deployment), then run `pnpm policy:doc`. "Code-fixed" knobs have no env var: change them in the schema.',
    '- **Clients:** `apps/web/src/config/policy.ts` and `apps/driver-app/lib/core/config/policy.dart`.',
    '',
    `${knobs.length} server knobs (${envCount} env-overridable) in ${categories.length} categories, ` +
      `${POLICY_RULES.length} cross-field rules, ${clients.web.length} web and ${clients.driver.length} driver-app knobs.`,
    '',
    '## Contents',
    '',
  );
  for (const c of categories) {
    const n = Object.keys(POLICY_SCHEMA[c]).length;
    lines.push(`- ${POLICY_CATEGORIES[c].title} (${n})`);
  }
  lines.push('- Cross-field rules', '- Client knobs (web, driver app)', '');

  for (const c of categories) {
    lines.push(`## ${POLICY_CATEGORIES[c].title}`, '', POLICY_CATEGORIES[c].blurb, '');
    lines.push(row(['Key', 'Env var', 'Default', 'Allowed', 'Unit', 'Description', 'Decision']));
    lines.push(row(['---', '---', '---', '---', '---', '---', '---']));
    for (const k of knobs.filter((e) => e.category === c)) {
      lines.push(
        row([
          `\`${k.key}\``,
          k.knob.env ? `\`${k.knob.env}\`` : '— (code-fixed)',
          formatDefault(k),
          formatAllowed(k.knob),
          k.knob.unit,
          k.knob.description,
          k.knob.decision,
        ]),
      );
    }
    lines.push('');
  }

  lines.push('## Cross-field rules', '', 'Checked at boot after every single knob is valid.', '');
  lines.push(row(['Rule', 'Env vars']));
  lines.push(row(['---', '---']));
  for (const r of POLICY_RULES) lines.push(row([r.description, r.keys.map((k) => `\`${envOf(k)}\``).join(', ')]));
  lines.push('');

  lines.push(
    '## Client knobs',
    '',
    'Server-owned values reach the clients in API responses and snapshots (quote fare, offer `ttlMs`,',
    'pool status, ride state). The knobs below are client-side decisions; `server-mirror` rows copy a server',
    'rule the client cannot read at runtime and must be kept in step with the table above.',
    '',
  );
  const clientTable = (title: string, file: string, set: ClientKnob[]) => {
    lines.push(`### ${title}`, '', `\`${file}\``, '');
    lines.push(row(['Key', 'Value', 'Unit', 'Source', 'Description', 'Decision']));
    lines.push(row(['---', '---', '---', '---', '---', '---']));
    for (const k of set) {
      lines.push(row([`\`${k.key}\``, `\`${k.value}\``, k.unit, k.source, k.description, k.decision]));
    }
    lines.push('');
  };
  clientTable('Web', 'apps/web/src/config/policy.ts', clients.web);
  clientTable('Driver app', 'apps/driver-app/lib/core/config/policy.dart', clients.driver);

  return lines.join('\n');
}

/** The env-example block: one commented section per category, every env knob at its default. */
export function renderEnvBlock(): string {
  const lines = [
    ENV_BLOCK_START,
    '# Business policy knobs. All optional; each line shows the default. The API validates',
    '# every value (and the cross-field rules) at boot and refuses to start on a bad one.',
    '# Overview, allowed ranges and the decision behind each default: docs/POLICY.md.',
  ];
  for (const c of Object.keys(POLICY_SCHEMA) as PolicyCategory[]) {
    const entries = policyKnobs().filter((k) => k.category === c && k.knob.env);
    if (entries.length === 0) continue;
    lines.push('#', `# ── ${POLICY_CATEGORIES[c].title} ──`);
    for (const entry of entries) {
      const { knob } = entry;
      const v = defaultValue(entry);
      const label = derivedLabel(knob);
      const derived = label ? `; default ${label}` : '';
      lines.push(`# ${knob.description} [${knob.unit}; ${formatAllowed(knob)}${derived}]`);
      lines.push(`# ${knob.env}=${Array.isArray(v) ? v.join(',') : String(v)}`);
    }
  }
  lines.push(ENV_BLOCK_END);
  return lines.join('\n');
}

/** Replace the generated block in an env example (or append it when absent). */
export function spliceEnvBlock(existing: string, block: string): string {
  const start = existing.indexOf(ENV_BLOCK_START);
  const end = existing.indexOf(ENV_BLOCK_END);
  if (start === -1 || end === -1 || end < start) {
    return `${existing.replace(/\s*$/, '')}\n\n${block}\n`;
  }
  return existing.slice(0, start) + block + existing.slice(end + ENV_BLOCK_END.length);
}

/** null when equal, else a one-line reason naming the first differing line. */
export function compareGenerated(name: string, expected: string, actual: string | null): string | null {
  if (actual === null) return `${name} is missing`;
  if (expected === actual) return null;
  const a = expected.split('\n');
  const b = actual.split('\n');
  const n = Math.max(a.length, b.length);
  for (let i = 0; i < n; i++) {
    if (a[i] !== b[i]) return `${name} is stale at line ${i + 1} (expected: ${JSON.stringify(a[i] ?? '<eof>')})`;
  }
  return `${name} differs`;
}
