#!/usr/bin/env node
/**
 * Record the ops/monitoring onboarding videos (M01-M06) against the running DEV stack.
 *
 *   pnpm demo:record:ops                       # all scenes, then rewrite docs/onboarding/videos/ops/INDEX.md
 *   pnpm demo:record:ops -- --scenes M02,M03   # a subset (INDEX.md is rebuilt from the mp4s on disk)
 *
 * Needs: dev stack up with the obs profile (pnpm dev:up), k6, ffmpeg, docker, and apps/web's Playwright
 * chromium (cd apps/web && npx playwright install chromium). See scripts/demo/ops/README.md.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { OUT_DIR, URLS, AREAS } from './config.mjs';
import { ensureDirs, log, assertAreaCIsolated, cleanLoad, probe, sh } from './lib.mjs';
import { SCENES } from './scenes.mjs';

const argv = process.argv.slice(2);
const sel = (() => { const i = argv.indexOf('--scenes'); return i === -1 ? Object.keys(SCENES) : argv[i + 1].split(',').map((s) => s.trim().toUpperCase()); })();
for (const id of sel) if (!SCENES[id]) { console.error(`unknown scene ${id}; known: ${Object.keys(SCENES).join(', ')}`); process.exit(2); }

async function preflight() {
  for (const [name, url] of [['api', `${URLS.api}/v1/health/live`], ['grafana', `${URLS.grafana}/api/health`], ['prometheus', `${URLS.prometheus}/-/healthy`]]) {
    const ok = await fetch(url).then((r) => r.ok).catch(() => false);
    if (!ok) throw new Error(`${name} is not reachable at ${url}: run \`pnpm dev:up\` (obs profile) first`);
  }
  const targets = await (await fetch(`${URLS.prometheus}/api/v1/targets`)).json();
  const down = targets.data.activeTargets.filter((t) => t.health !== 'up').map((t) => t.labels.job);
  if (down.length) log(`WARN prometheus targets not up: ${down.join(', ')}`);
  assertAreaCIsolated();
  sh('which', ['k6']); sh('which', ['ffmpeg'], { allowFail: false });
}

function buildIndex() {
  const rows = [], blocks = [];
  for (const [id, s] of Object.entries(SCENES)) {
    const f = join(OUT_DIR, `${id}-${s.slug}.mp4`);
    if (!existsSync(f)) { rows.push(`| ${id} | ${s.title} | - | not recorded yet | - |`); continue; }
    const { seconds, mb } = probe(f);
    rows.push(`| ${id} | [${s.title}](${id}-${s.slug}.mp4) | ${seconds} s | ${mb} MB | \`${s.regen}\` |`);
    blocks.push(`### ${id} - ${s.title}\n\n- File: \`${id}-${s.slug}.mp4\` (${seconds} s, ${mb} MB, 1280x720 H.264)\n- Shows: ${s.card.join('; ')}\n- States / transitions: ${s.states}\n- Regenerate: \`${s.regen}\``);
  }
  const A = AREAS;
  const md = `# Ops and monitoring videos (M01-M06)

Generated by \`scripts/demo/ops/record.mjs\` (see [scripts/demo/ops/README.md](../../../../scripts/demo/ops/README.md)); do not edit by hand,
re-run \`pnpm demo:record:ops\`. All recordings are of the **dev** stack, headless Chromium 1280x720, with a caption bar naming
what is on screen. Related reading: [80-infrastructure/observability.md](../../../../80-infrastructure/observability.md),
[docs/operations/recovery-runbook.md](../../../operations/recovery-runbook.md), [docs/POLICY.md](../../../POLICY.md).

| ID | Video | Length | Size | Regenerate |
|---|---|---|---|---|
${rows.join('\n')}

${blocks.join('\n\n')}

## Facts a viewer should know

- **Traffic is synthetic.** Dashboards are fed by \`infra/load/workload.js\` (k6) with fixture identities from
  \`infra/load/prepare-dev.mjs\` (dev-only signed tokens; refuses non-loopback / production). The simulated drivers and riders are
  parked in Guwahati **Area C** (${A.C.lat}, ${A.C.lng}), more than \`dispatch.r2Meters\` (4 km, [docs/POLICY.md](../../../POLICY.md)) from
  Area A (${A.A.lat}, ${A.A.lng}) and Area B (${A.B.lat}, ${A.B.lng}) where the app demos run, so load never steals or receives real demo offers.
  Override the centre for the loader with \`LOAD_BASE_LAT\` / \`LOAD_BASE_LNG\`.
- **Dev-only credentials** (never reuse): Grafana \`admin\` / \`admin\` (\`docker-compose.dev.yml\`); throwaway Uptime Kuma for M04 \`admin\` / \`admin1234!\`
  (created and destroyed by the harness on port 3013; the long-lived dev Kuma on :3003 keeps whatever login was chosen at its first run).
- **M05** injects one clearly labelled \`RcabDemoAlert\` straight into Alertmanager (it does not come from a rule) and resolves it. Alertmanager has
  no host port; the harness opens a throwaway \`socat\` forward container for the recording and removes it.
- **M06** executes the commands for real (the pool shown is one shared pool the harness opens in Area C, then deletes), then renders the captured output as a typed
  replay, because a headless browser cannot screen-capture a real terminal. Long outputs are trimmed with an explicit "lines elided" marker.
- **Phase-0 gaps visible in the videos:** Alertmanager's receiver \`default\` has no notifier, so alerts are visible but nobody is paged; the redis/postgres
  exporters exist only in the dev compose (the postgres exporter needs the DB credential, a secrets decision for prod).
`;
  writeFileSync(join(OUT_DIR, 'INDEX.md'), md);
  log('wrote INDEX.md');
}

(async () => {
  ensureDirs();
  await preflight();
  try {
    for (const id of sel) {
      log(`=== ${id} ${SCENES[id].title}`);
      const out = await SCENES[id].run();
      const p = probe(out);
      log(`${id} -> ${out} (${p.seconds} s, ${p.mb} MB)`);
      if (p.mb > 12 || p.seconds < 15 || p.seconds > 150) log(`WARN ${id} outside the 15-150 s / 12 MB rules`);
    }
  } finally {
    cleanLoad();
    buildIndex();
  }
})().catch((e) => { console.error(e); process.exit(1); });
